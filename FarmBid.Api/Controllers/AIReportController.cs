
using System.Security.Claims;
using FarmBid.Api.DTOs.AI;
using FarmBid.Api.Services.AI;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;
using FarmBid.Api.Data;

namespace FarmBid.Api.Controllers;

[ApiController]
[Route("api/ai-reports")]
[Authorize(Roles = "Farmer,Buyer")]
public class AIReportController : ControllerBase
{
    private readonly AIReportService _aiReportService;
    private readonly FarmBidDbContext _context;

    public AIReportController(
        AIReportService aiReportService,
        FarmBidDbContext context)
    {
        _aiReportService = aiReportService;
        _context = context;
    }

    // GET: api/ai-reports
    // Retrieves reports generated by the authenticated user.
    [HttpGet]
    public async Task<IActionResult> GetMyReports()
    {
        var userIdClaim = User.FindFirstValue(
            ClaimTypes.NameIdentifier);

        if (!long.TryParse(userIdClaim, out long userId))
            return Unauthorized();

        var reports = await _context.AiMarketReports
            .AsNoTracking()
            .Where(r => r.GeneratedBy == userId)
            .OrderByDescending(r => r.GeneratedAt)
            .Select(r => new MarketReportDto
            {
                ReportId = r.ReportId,
                ReportType = r.ReportType,
                ReportContent = r.ReportContent,
                ModelName = r.ModelName,
                GeneratedAt = r.GeneratedAt
            })
            .ToListAsync();

        return Ok(reports);
    }

    // GET: api/ai-reports/{id}
    // Retrieves one report belonging to the authenticated user.
    [HttpGet("{id}")]
    public async Task<IActionResult> GetReportById(long id)
    {
        var userIdClaim = User.FindFirstValue(
            ClaimTypes.NameIdentifier);

        if (!long.TryParse(userIdClaim, out long userId))
            return Unauthorized();

        var report = await _context.AiMarketReports
            .AsNoTracking()
            .Where(r => r.ReportId == id &&
                        r.GeneratedBy == userId)
            .Select(r => new MarketReportDto
            {
                ReportId = r.ReportId,
                ReportType = r.ReportType,
                ReportContent = r.ReportContent,
                ModelName = r.ModelName,
                GeneratedAt = r.GeneratedAt
            })
            .FirstOrDefaultAsync();

        if (report == null)
            return NotFound(new
            {
                message = "Report not found."
            });

        return Ok(report);
    }

    // POST: api/ai-reports/generate
    // Generates and saves a new overall market report.
    [HttpPost("generate")]
    public async Task<IActionResult> GenerateOverallReport(
        CancellationToken cancellationToken)
    {
        var userIdClaim = User.FindFirstValue(
            ClaimTypes.NameIdentifier);

        if (!long.TryParse(userIdClaim, out long userId))
            return Unauthorized();

        try
        {
            var report = await _aiReportService
                .GenerateOverallReportAsync(
                    userId,
                    cancellationToken);

            return Ok(report);
        }
        catch (HttpRequestException)
        {
            return StatusCode(502, new
            {
                message = "Unable to generate the AI report. Please try again later."
            });
        }
        catch (OperationCanceledException)
            when (cancellationToken.IsCancellationRequested)
        {
            return StatusCode(499, new
            {
                message = "The report generation request was cancelled."
            });
        }
    }
}
